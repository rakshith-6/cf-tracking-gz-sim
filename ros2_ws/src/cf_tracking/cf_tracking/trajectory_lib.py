"""
Feasible reference trajectories generation script

A trajectory is a Trajectory object: pos(t)->(3,), vel(t)->(3,)(central
difference), yaw(t)->float, yaw_rate(t)->float, and .duration.

Crazyflie-scaled defaults: extents ~1.5 m, altitude ~1.0 m, speeds 0.3-1.2 m/s,
MAX_ACCEL 4.0 m/s^2 (~22 deg tilt limit, T/W is ~1.8)
"""
import math

import numpy as np
from scipy.interpolate import make_interp_spline

MAX_ACCEL = 4.0 
YAW_RATE_MAX = 1.0 # in rad/s, ~ 57deg/s 
Z_MIN = 0.3 # in m, ground clearance for every reference point
_EPS = 1e-4 # in s, central-difference half-step


class Trajectory:
    def __init__(self, pos_fn, duration, yaw_fn=None, yaw_rate_fn=None):
        self._pos = pos_fn
        self.duration = float(duration)
        self._yaw = yaw_fn or (lambda t: 0.0)
        self._yaw_rate = yaw_rate_fn or (lambda t: 0.0)

    def pos(self, t):
        return np.asarray(self._pos(np.clip(t, 0.0, self.duration)), float)

    def vel(self, t):
        t0, t1 = max(0.0, t - _EPS), min(self.duration, t + _EPS)
        if t1 <= t0:
            return np.zeros(3)
        return (self.pos(t1) - self.pos(t0)) / (t1 - t0)

    def yaw(self, t):
        return float(self._yaw(np.clip(t, 0.0, self.duration)))

    def yaw_rate(self, t):
        return float(self._yaw_rate(np.clip(t, 0.0, self.duration)))

def _peaks(pos_fn, duration, n=2000):
    '''
    Function to estimate the peak velocity and acceleration of a trajectory
    '''
    t = np.linspace(0.0, duration, n)
    p = np.array([pos_fn(ti) for ti in t])
    dt = t[1] - t[0]
    v = np.gradient(p, dt, axis=0)
    a = np.gradient(v, dt, axis=0)
    return np.linalg.norm(v, axis=1).max(), np.linalg.norm(a, axis=1).max()

def _time_scale(pos_fn, duration, max_speed):
    '''
    Time scaling/parameterization: 
    - Making sure trajectories peak speed <= max_speed and peak accel <= MAX_ACCEL
    - If 's' is the scale factor, pos(t) -> pos(t/s) slows speed by s and accel by s^2
    '''
    v_pk, a_pk = _peaks(pos_fn, duration)
    s = max(1.0, v_pk / max_speed if max_speed > 0 else 1.0,
            math.sqrt(a_pk / MAX_ACCEL) if a_pk > 0 else 1.0)
    return (lambda t: pos_fn(t / s)), duration * s

"""
Trajectory primitives fu's: harmonic, spline, circle, lissajous, aggressive_sweep, 
rose, superellipse

All fu returns (pos_fn, duration)
"""

def make_harmonic(rng, max_speed=0.8, altitude=1.0, n_modes=4,
                  freq_min_hz=0.05, freq_max_hz=0.5,
                  max_extent=1.2, delta_z=0.3, duration=30.0):
    '''
    Traj generated by defining x, y and z as sum of n_modes sine waves

    We generate random amplitudes, frequencies and phases
    '''
    amps, freqs, phases = [], [], []
    for ax in range(3):
        a = rng.uniform(0.3, 1.0, n_modes)
        a *= (max_extent if ax < 2 else delta_z) / a.sum()
        amps.append(a)
        freqs.append(rng.uniform(freq_min_hz, freq_max_hz, n_modes))
        phases.append(rng.uniform(0, 2 * np.pi, n_modes))
    amps, freqs, phases = map(np.array, (amps, freqs, phases))

    def pos(t):
        s = np.sin(2 * np.pi * freqs * t + phases) # (3, n_modes)
        off = np.sin(phases) # To starts at origin, we subtract this
        p = ((s - off) * amps).sum(axis=1) 
        return np.array([p[0], p[1], max(altitude + p[2], Z_MIN)])
    
    return _time_scale(pos, duration, max_speed)

def make_spline(rng, max_speed=0.8, altitude=1.0, n_waypoints=8,
                max_extent=1.2, delta_z=0.3, duration=30.0):
    '''
    We fit a quintic B-spline through random waypoints
    '''
    wp = np.zeros((n_waypoints, 3))
    wp[1:-1, 0] = rng.uniform(-max_extent, max_extent, n_waypoints - 2)
    wp[1:-1, 1] = rng.uniform(-max_extent, max_extent, n_waypoints - 2)
    wp[1:-1, 2] = rng.uniform(-delta_z, delta_z, n_waypoints - 2)
    wp[:, 2] = np.maximum(altitude + wp[:, 2], Z_MIN)
    wp[0, 2] = wp[-1, 2] = altitude
    tk = np.linspace(0.0, duration, n_waypoints)
    # Boundary cond: Both the ends of the spline will have zero vel and accel
    bc = ([(1, np.zeros(3)), (2, np.zeros(3))],
          [(1, np.zeros(3)), (2, np.zeros(3))])
    spl = make_interp_spline(tk, wp, k=5, bc_type=bc)

    def pos(t):
        p = spl(np.clip(t, 0.0, duration))
        return np.array([p[0], p[1], max(p[2], Z_MIN)])

    return _time_scale(pos, duration, max_speed)

def make_circle(rng, max_speed=0.6, radius=0.6, altitude=1.0, duration=25.0):
    '''
    Circle starting at (0,0)
    '''
    omega = max_speed / radius
    def pos(t):
        return np.array([radius * math.sin(omega * t),
                         radius * (1.0 - math.cos(omega * t)),
                         altitude])
    
    return _time_scale(pos, duration, max_speed)

def make_lissajous(rng, max_speed=0.8, altitude=1.0, freq_ratio=(3, 2, 1),
                   base_freq_hz=0.1, amp_xy=1.0, amp_z=0.25, duration=30.0):
    rx, ry, rz = freq_ratio
    w = 2 * np.pi * base_freq_hz
    ph = rng.uniform(0, 2 * np.pi, 3)
    def pos(t):
        return np.array([
            amp_xy * (math.sin(rx * w * t + ph[0]) - math.sin(ph[0])),
            amp_xy * (math.sin(ry * w * t + ph[1]) - math.sin(ph[1])),
            max(altitude + amp_z * (math.sin(rz * w * t + ph[2])
                                    - math.sin(ph[2])), Z_MIN)])

    return _time_scale(pos, duration, max_speed)

def make_aggressive_sweep(rng, max_speed=1.0, v_start=0.2, radius=0.6,
                          altitude=1.0, duration=25.0):
    '''
    Circle traj where tangential speed is ramped linearly. max_speed is 
    the final tangential speed, accel cap enforced by _time_scale
    '''
    v_end = max_speed
    accel_t = (v_end - v_start) / duration

    def pos(t):
        # arc length s(t) = v_start*t + 0.5*at^2 so, angle = s/r
        ang = (v_start * t + 0.5 * accel_t * t * t) / radius
        return np.array([radius * math.sin(ang),
                         radius * (1.0 - math.cos(ang)),
                         altitude])

    return _time_scale(pos, duration, v_end)

def make_rose(rng, max_speed=0.8, k=3, a=1.0, altitude=1.0,
              delta_z=0.2, duration=30.0):
    '''
    Rose curve, r = a*cos(k*theta) in polar coordinates, we also add 
    a gentle oscillation in altitude to make the traj 3D
    '''
    w = 2 * np.pi / duration * 2  # *2 for two passes
    phz = rng.uniform(0, 2 * np.pi)
    def pos(t):
        th = w * t
        r = a * math.cos(k * th)
        return np.array([
            r * math.cos(th), r * math.sin(th),
            max(altitude + delta_z * (math.sin(2 * w * t + phz)
                                      - math.sin(phz)), Z_MIN)])

    return _time_scale(pos, duration, max_speed)

def make_superellipse(rng, max_speed=0.8, A=1.2, B=0.8, n=4,
                      altitude=1.0, duration=30.0):
    '''
    Superellipse traj: |x/A|^n + |y/B|^n = 1, n = 2 is a ellipse, for
    n>2 we get rectangle with round corners

    Angle reparameterization by arc length for const grd speed: 
    Naive parameterization has unbounded velocity at the corners as,
    (d/dtheta |cos(theta)|^(2/n) diverges for n > 2)
    '''
    th = np.linspace(0.0, 2 * np.pi, 4000)
    x = A * np.sign(np.cos(th)) * np.abs(np.cos(th)) ** (2.0 / n)
    y = B * np.sign(np.sin(th)) * np.abs(np.sin(th)) ** (2.0 / n)
    s = np.concatenate([[0.0], np.cumsum(np.hypot(np.diff(x), np.diff(y)))])
    total = s[-1]
    laps = 2
    def pos(t):
        si = (t / duration * laps * total) % total
        return np.array([np.interp(si, s, x) - A, np.interp(si, s, y), altitude])

    return _time_scale(pos, duration, max_speed)

PRIMITIVES = {
    'harmonic': make_harmonic,
    'spline': make_spline,
    'circle': make_circle,
    'lissajous': make_lissajous,
    'aggressive_sweep': make_aggressive_sweep,
    'rose': make_rose,
    'superellipse': make_superellipse,
}

"""
Yaw modes: fixed, sinusoidal, rate_const, velocity

Fixed : Quadrotor has no yaw motion, i.e, yaw and yaw rate is zero
Sinusoidal : Quadrotor oscillates about a mean position as it moves
rate_const : Quadrotor rotates with a constant yaw rate as it moves
velocity : Quadrotor nose points along the velocity or direction of motion
"""

def build_yaw(mode, pos_fn, duration, rng, yaw_const=0.0,
              yaw_amp=0.5, yaw_freq_hz=0.1, yaw_rate=0.3):
    '''
    Returns yaw(t) and yaw_rate(t)
    '''
    if mode == 'fixed':
        return (lambda t: yaw_const), (lambda t: 0.0)
    if mode == 'sinusoidal':
        w = 2 * np.pi * yaw_freq_hz
        amp = min(yaw_amp, YAW_RATE_MAX / w)
        return (lambda t: amp * math.sin(w * t)), \
               (lambda t: amp * w * math.cos(w * t))
    if mode == 'rate_const':
        r = math.copysign(min(abs(yaw_rate), YAW_RATE_MAX), yaw_rate)
        return (lambda t: r * t), (lambda t: r)
    if mode == 'velocity':
        dt = 0.01
        n = int(duration / dt) + 2
        yaws = np.zeros(n)
        for i in range(1, n):
            t = i * dt
            v = (np.asarray(pos_fn(min(t + _EPS, duration)))
                 - np.asarray(pos_fn(max(t - _EPS, 0.0)))) / (2 * _EPS)
            target = math.atan2(v[1], v[0]) if np.hypot(v[0], v[1]) > 0.05 \
                else yaws[i - 1]
            err = (target - yaws[i - 1] + np.pi) % (2 * np.pi) - np.pi
            yaws[i] = yaws[i - 1] + np.clip(err, -YAW_RATE_MAX * dt,
                                            YAW_RATE_MAX * dt)
        rates = np.gradient(yaws, dt)

        def yaw_fn(t):
            return float(np.interp(t, np.arange(n) * dt, yaws))

        def rate_fn(t):
            return float(np.interp(t, np.arange(n) * dt, rates))
        return yaw_fn, rate_fn
    raise ValueError(f'unknown yaw mode {mode}')

def build_trajectory(primitive, yaw_mode='fixed', seed=0, **kwargs):
    '''
    Build a complete trajectory. Based on the parameter name we split kwargs 
    between the prim_kw and yaw_kw. We return a Trajectory object
    '''
    rng = np.random.default_rng(seed)
    factory = PRIMITIVES[primitive]
    
    import inspect as _inspect
    
    prim_names = set(_inspect.signature(factory).parameters)
    yaw_names = {'yaw_const', 'yaw_amp', 'yaw_freq_hz', 'yaw_rate'}
    prim_kw = {k: v for k, v in kwargs.items() if k in prim_names}
    yaw_kw = {k: v for k, v in kwargs.items() if k in yaw_names}
    
    pos_fn, duration = factory(rng, **prim_kw)
    yaw_fn, yaw_rate_fn = build_yaw(yaw_mode, pos_fn, duration, rng, **yaw_kw)
    
    return Trajectory(pos_fn, duration, yaw_fn, yaw_rate_fn)